// Generator functions to shuffle and compose drills
export function getRandomSlice<T>(arr: T[], count: number): T[] {
  const shuffled = [...arr].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, Math.min(count, arr.length));
}

const THAI_COMBINING_SET = new Set(['่', '้', '๊', '๋', 'ิ', 'ี', 'ึ', 'ื', 'ุ', 'ู', 'ั', '็', '์', 'ํ', 'ฺ']);

export function generateDrillText(
  keys: string[],
  wordLength: number = 4,
  wordCount: number = 10
): string {
  const isThai = keys.some(k => /[\u0E00-\u0E7F]/.test(k));
  if (!isThai) {
    const words: string[] = [];
    for (let i = 0; i < wordCount; i++) {
      let word = '';
      for (let j = 0; j < wordLength; j++) {
        const randomKey = keys[Math.floor(Math.random() * keys.length)];
        word += randomKey;
      }
      words.push(word);
    }
    return words.join(' ');
  }

  // Thai specific generator: ensures combining marks (vowels/tones) always follow a consonant
  const combining = keys.filter(k => THAI_COMBINING_SET.has(k));
  let baseKeys = keys.filter(k => !THAI_COMBINING_SET.has(k) && k !== ' ');
  if (baseKeys.length === 0) {
    baseKeys = ['ฟ', 'ห', 'ก', 'ด', 'ส', 'ว'];
  }

  const words: string[] = [];
  for (let i = 0; i < wordCount; i++) {
    let word = '';
    // Always start with a base consonant
    word += baseKeys[Math.floor(Math.random() * baseKeys.length)];

    while (word.length < wordLength) {
      // Chance of attaching a combining mark if available and previous char was a base consonant
      const lastChar = word[word.length - 1];
      if (combining.length > 0 && !THAI_COMBINING_SET.has(lastChar) && Math.random() < 0.45) {
        word += combining[Math.floor(Math.random() * combining.length)];
      } else {
        word += baseKeys[Math.floor(Math.random() * baseKeys.length)];
      }
    }
    words.push(word.normalize('NFC'));
  }

  return words.join(' ');
}
